#!/usr/bin/env bash
# Regenerates src/test/resources/com/carddemo/domain/date/csutldtc-gnucobol.txt by running the
# unmodified app/cbl/CSUTLDTC.cbl under GnuCOBOL 3.x with ceedays_stub.c in place of LE CEEDAYS.
# One line per case: feedback-token-hex|LS-DATE|LS-DATE-FORMAT|LS-RESULT as hex|RETURN-CODE
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../../../../../.." && pwd)"
out="$here/../../resources/com/carddemo/domain/date/csutldtc-gnucobol.txt"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cobc -x -std=ibm -fstatic-call -o "$work/csutldrv" \
  "$here/CSUTLDRV.cbl" "$repo/app/cbl/CSUTLDTC.cbl" "$here/ceedays_stub.c"

tokens=(
  000000000000000000000000   # FC-INVALID-DATE (all zero: success)
  000309CB59C3C5C500000000   # FC-INSUFFICIENT-DATA  2507
  000309CC59C3C5C500000000   # FC-BAD-DATE-VALUE     2508
  000309CD59C3C5C500000000   # FC-INVALID-ERA        2509
  000309D159C3C5C500000000   # FC-UNSUPP-RANGE       2513
  000309D559C3C5C500000000   # FC-INVALID-MONTH      2517
  000309D659C3C5C500000000   # FC-BAD-PIC-STRING     2518
  000309D859C3C5C500000000   # FC-NON-NUMERIC-DATA   2520
  000309D959C3C5C500000000   # FC-YEAR-IN-ERA-ZERO   2521
  000209C459C3C5C500000000   # any other token: WHEN OTHER (sev 2, msg 2500)
)
cases=(
  "2024-02-29|YYYY-MM-DD"
  "20240229  |YYYYMMDD  "
)

{
  echo "# Generated by src/test/cobol/csutldtc/generate.sh from app/cbl/CSUTLDTC.cbl ($(cobc --version | head -1))."
  echo "# feedback-token-hex|LS-DATE|LS-DATE-FORMAT|LS-RESULT hex|RETURN-CODE"
  for fc in "${tokens[@]}"; do
    for c in "${cases[@]}"; do
      d="${c%%|*}"; f="${c#*|}"
      line="$(CEEDAYS_FC="$fc" CSUTLDTC_DATE="$d" CSUTLDTC_FORMAT="$f" "$work/csutldrv")"
      echo "$fc|$d|$f|${line% *}|${line##* }"
    done
  done
} > "$out"
echo "wrote $out"
