package com.carddemo.online.coactvwc;

/** The DFHBMSCA attribute/colour constants COACTVWC uses, as their EBCDIC byte values. */
final class Dfhbmsca {

    /** DFHBMFSE: unprotected, MDT on (X'C8'). */
    static final int DFHBMFSE = 0xC8;
    /** DFHBMDAR: dark (X'4C'). */
    static final int DFHBMDAR = 0x4C;
    /** DFHDFCOL: default colour (X'00'). */
    static final int DFHDFCOL = 0x00;
    /** DFHRED (X'F2'). */
    static final int DFHRED = 0xF2;
    /** DFHNEUTR (X'F7'). */
    static final int DFHNEUTR = 0xF7;

    private Dfhbmsca() {
    }
}
