package com.carddemo.batch.posttran.batch;

import static org.assertj.core.api.Assertions.assertThat;

import com.carddemo.batch.posttran.TestClockConfig;
import com.carddemo.batch.posttran.TestData;
import com.carddemo.batch.posttran.cobol.FixedRecordFiles;
import com.carddemo.batch.posttran.cobol.Sysout;
import com.carddemo.batch.posttran.record.RejectRecord;
import com.carddemo.batch.posttran.seed.VsamDatasets;
import com.carddemo.batch.posttran.seed.VsamDatasets.Seed;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.EnumSource;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Import;

/**
 * Runs POSTTRAN against the shipped seed data and compares every output with what the original
 * CBTRN02C produced under GnuCOBOL (src/test/resources/golden, regenerated by
 * tools/gnucobol/run-cobol-posttran.sh). TRAN-PROC-TS is the wall clock, so it is masked on both sides.
 */
@SpringBootTest(properties = {"posttran.run-on-startup=false", "spring.datasource.url=jdbc:h2:mem:golden-test"})
@Import(TestClockConfig.class)
class GoldenMasterTest {

    private static final int PROC_TS_OFFSET = 304;
    private static final int PROC_TS_LENGTH = 26;

    @Autowired
    private VsamDatasets datasets;
    @Autowired
    private PostTranLauncher launcher;
    @Autowired
    private Sysout sysout;

    @TempDir
    Path tmp;

    @AfterEach
    void restoreSysout() {
        sysout.redirect(System.out);
    }

    @ParameterizedTest
    @EnumSource(Seed.class)
    void matchesCobolOutput(Seed seed) throws IOException {
        Path golden = Path.of("src/test/resources/golden", seed.name().toLowerCase(Locale.ROOT));
        datasets.load(TestData.dataDir(), seed);
        ByteArrayOutputStream captured = new ByteArrayOutputStream();
        sysout.redirect(new PrintStream(captured, true, StandardCharsets.UTF_8));
        Path rejects = tmp.resolve("dalyrejs");

        PostTranResult result = launcher.run(seed.dalytran(TestData.dataDir()), rejects, seed.format);

        assertThat(result.returnCode()).isEqualTo(Integer.parseInt(Files.readString(golden.resolve("return-code.txt")).trim()));
        assertThat(result.transactionCount()).isEqualTo(300);
        assertThat(result.rejectCount()).isEqualTo(38);
        assertThat(captured.toString(StandardCharsets.UTF_8).lines().toList())
                .containsExactlyElementsOf(lines(golden.resolve("sysout.txt")));
        assertThat(FixedRecordFiles.read(rejects, seed.format, RejectRecord.LENGTH))
                .containsExactlyElementsOf(lines(golden.resolve("dalyrejs.txt")));
        assertThat(datasets.unloadTransactions().stream().map(GoldenMasterTest::maskProcTs).toList())
                .containsExactlyElementsOf(lines(golden.resolve("transact.txt")));
        assertThat(datasets.unloadAccounts()).containsExactlyElementsOf(lines(golden.resolve("acctdata.txt")));
        assertThat(datasets.unloadTranCatBalances()).containsExactlyElementsOf(lines(golden.resolve("tcatbal.txt")));
    }

    private static String maskProcTs(String record) {
        return record.substring(0, PROC_TS_OFFSET) + "#".repeat(PROC_TS_LENGTH)
                + record.substring(PROC_TS_OFFSET + PROC_TS_LENGTH);
    }

    private static List<String> lines(Path file) throws IOException {
        return Files.readString(file, StandardCharsets.ISO_8859_1).lines().toList();
    }
}
