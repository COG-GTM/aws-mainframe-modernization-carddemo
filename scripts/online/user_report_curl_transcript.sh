# User administration (CU00..CU03) and transaction report (CR00) curl transcript against a running
# `docker compose up -d --build --wait` stack (fresh volume).
# Usage: scripts/online/user_report_curl_transcript.sh [base-url] > docs/validation/online/user-admin-reports-curl.md
# Seeds TRANSACT by running POSTTRAN in the app container (set SEED=0 to skip); tokens are redacted.
set -euo pipefail
BASE=${1:-http://localhost:${CARDDEMO_HTTP_PORT:-8080}}
API=$BASE/api/v1
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
