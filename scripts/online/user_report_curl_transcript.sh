# step <title> <curl args...>: prints the request (bearer redacted), status and pretty JSON; leaves the body in $BODY
step() {
  local title=$1; shift
  printf '### %s\n$ curl %s\n' "$title" "$(shown "$@")"
  local code
  code=$(curl -s -o "$BODY" -w '%{http_code}' "$@")
  printf 'HTTP %s\n' "$code"
  jq '(.. | objects | select(has("token")) | .token) |= "<redacted>"' "$BODY" 2>/dev/null || cat "$BODY"
  printf '\n'
}

shown() {
  local out=()
  for a in "$@"; do
    case $a in
      "Authorization: Bearer "*) out+=("'Authorization: Bearer \$TOKEN'") ;;
      *[[:space:]\"{}?\&]*) out+=("'$a'") ;;
      *) out+=("$a") ;;
    esac
  done
  printf '%s' "${out[*]}"
}

login() {
  curl -s "$API/auth/login" -H 'Content-Type: application/json' \
    -d "{\"userId\":\"$1\",\"password\":\"PASSWORD\"}" | jq -r .token
}

# poll <execution id>: GET the status until COMPLETED/FAILED; prints each state change and the final body
poll() {
  local last="" state
  printf '### Poll report execution %s until it finishes\n$ curl %s/reports/transactions/%s  (every 0.5 s)\n' \
    "$1" "$API" "$1"
  for _ in $(seq 1 240); do
    curl -s -o "$BODY" "$API/reports/transactions/$1" -H "$AA"
    state=$(jq -r .status "$BODY")
    [ "$state" != "$last" ] && printf 'status %s\n' "$state" && last=$state
    case $state in COMPLETED|FAILED) break ;; esac
    sleep 0.5
  done
  jq 'if .report then .report.lines |= (.[:4] + ["... (" + ((length - 4) | tostring) + " more lines)"]) else . end' \
    "$BODY"
  printf '\n'
}

